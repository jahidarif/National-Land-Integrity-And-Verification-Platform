from __future__ import annotations
from abc import ABC, abstractmethod
from datetime import datetime
from typing import Protocol
from app.domain.entities import Conversation, Message, RefreshToken, User


class IUserRepository(Protocol):
    def get_by_id(self, user_id: str) -> User | None: ...
    def get_by_email(self, email: str) -> User | None: ...
    def add(self, user: User) -> None: ...

class IConversationRepository(Protocol):
    def get_for_user(self, conversation_id: str, user_id: str) -> Conversation | None: ...
    def list_for_user(self, user_id: str, limit: int = 100) -> list[Conversation]: ...
    def add(self, conversation: Conversation) -> None: ...
    def delete(self, conversation: Conversation) -> None: ...

class IMessageRepository(Protocol):
    def list_for_conversation(self, conversation_id: str) -> list[Message]: ...
    def add(self, message: Message) -> None: ...
    def count_for_conversation(self, conversation_id: str) -> int: ...

class IRefreshTokenRepository(Protocol):
    def get_by_jti(self, jti: str) -> RefreshToken | None: ...
    def add(self, token: RefreshToken) -> None: ...

class IUnitOfWork(ABC):
    users: IUserRepository
    conversations: IConversationRepository
    messages: IMessageRepository
    refresh_tokens: IRefreshTokenRepository
    @abstractmethod
    def commit(self) -> None: ...
    @abstractmethod
    def rollback(self) -> None: ...
    @abstractmethod
    def refresh(self, entity: object) -> None: ...
    @abstractmethod
    def flush(self) -> None: ...
